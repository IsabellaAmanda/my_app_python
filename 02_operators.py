### Operadores Aritmeticos###

print(3 + 4) #suma
print(3 - 4) #resta
print(3 * 4) #multiplicacion
print(3 / 4) #division decimal
print(10 % 2) #modulo => resto
print(10 // 3) #modulo => cociente
print(2 ** 4 ) #exponencial
print(2 ** 4 + 3 - 7 / 1 // 4) #exponencial

